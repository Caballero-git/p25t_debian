#!/bin/bash
# test_28.sh - rear camera: Rockchip's own init sequence, written by hand.
#
# test_24..27 (2026-10-07): during the stream the sensor has power, clock
# (24 MHz) and PWDN high; the driver's start sequence reaches it (0xfc reads
# 0x8e); the front-camera pins are not its reset. But the sensor never puts
# a high-speed clock on the MIPI lanes. Our driver uses Intel's register
# tables plus an OTP step; Android on this tablet ran Rockchip's BSP driver,
# whose sequence is different: 159 writes (sensor setup + 2592x1944 mode),
# then page 0, 0x3e = 0x91 (stream on).
#
# While our driver keeps the sensor powered (a stream in the background),
# this writes the BSP sequence over I2C (bus 2, 0x37, forced next to the
# driver), then stream-on, and watches the CSI-2 receiver for the
# high-speed clock. Frames will not be captured (VICAP waits for 1296x972,
# BSP sends 2592x1944) - the HS clock alone answers the question:
#   HS clock ACTIVE  -> the sensor works; our driver's sequence is the problem
#   still off        -> something outside the register sequence (clock pin,
#                       board wiring) - back to hardware
# Writes only to the camera sensor.
#
#   cd ~/tests
#   sudo bash test_28.sh | tee result_28.txt

set -u
[ "$(id -u)" -eq 0 ] || { echo "ABORT: run with sudo"; exit 1; }
W=1296; H=972; FMT=SGRBG10_1X10
M=/dev/media0
echo "=== rear camera BSP sequence by hand (test_28) ==="
date; uname -v

VID=$(media-ctl -d $M -e "rkcif-mipi0-id0")
media-ctl -d $M -V "\"gc5035 2-0037\":0 [fmt:$FMT/${W}x$H field:none]" &&
media-ctl -d $M -V "\"dw-mipi-csi2rx fdfb0000.csi\":0 [fmt:$FMT/${W}x$H field:none]" &&
media-ctl -d $M -V "\"rkcif-mipi0\":0 [fmt:$FMT/${W}x$H field:none]" &&
media-ctl -d $M -V "\"rkcif-mipi0\":1 [fmt:$FMT/${W}x$H field:none crop:(0,0)/${W}x$H]" || echo "WARNING: media-ctl -V failed"
v4l2-ctl -d "$VID" --set-fmt-video=width=$W,height=$H,pixelformat=BA10 >/dev/null

cat > /tmp/p25t_bsp.py <<'EOF'
