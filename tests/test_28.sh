fd = os.open("/dev/i2c-2", os.O_RDWR)
fcntl.ioctl(fd, I2C_SLAVE_FORCE, 0x37)
def wr(r, v): os.write(fd, bytes((r, v)))
def rd(r):
    os.write(fd, bytes((r,))); return os.read(fd, 1)[0]
mfd = os.open("/dev/mem", os.O_RDONLY | os.O_SYNC)
def phy():
    m = mmap.mmap(mfd, 0x1000, mmap.MAP_SHARED, mmap.PROT_READ, offset=0xfdfb0000)
    p, e1, e2 = (struct.unpack("<I", m[o:o + 4])[0] for o in (0x14, 0x20, 0x24)); m.close()
    return "PHY_STATE 0x%03x (HS clock %s, data stop 0x%x) ERR1 0x%x ERR2 0x%x" % (
        p, "ACTIVE" if p & 0x100 else "off", (p >> 4) & 0xf, e1, e2)
def show(t):
    wr(0xfe, 0)
    print("%-28s 0xfc=%02x 0x3e=%02x 0x41=%02x 0x42=%02x | %s" % (
        t, rd(0xfc), rd(0x3e), rd(0x41), rd(0x42), phy()))
print("sequence: %d writes, last %s" % (len(SEQ), ["%02x=%02x" % p for p in SEQ[-3:]]))
show("before")
for r, v in SEQ:
    wr(r, v)
time.sleep(0.05)
show("after BSP sequence")
wr(0xfe, 0x00); wr(0x3e, 0x91)
for i in range(4):
    time.sleep(0.25)
    show("stream on +%d ms" % (250 * (i + 1)))
EOF

echo; echo "--- start stream in the background (keeps the sensor powered) ---"
timeout 15 v4l2-ctl -d "$VID" --stream-mmap --stream-count=3 --stream-to=/dev/null >/dev/null 2>&1 &
BG=$!
sleep 2
echo "runtime PM: $(cat /sys/bus/i2c/devices/2-0037/power/runtime_status)"
python3 /tmp/p25t_bsp.py
kill $BG 2>/dev/null; wait $BG 2>/dev/null
echo; echo "--- kernel log ---"; dmesg | tail -8
rm -f /tmp/p25t_bsp.py
echo "=== done ==="
