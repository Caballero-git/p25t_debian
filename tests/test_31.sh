i2c = os.open("/dev/i2c-2", os.O_RDWR)
fcntl.ioctl(i2c, 0x0706, 0x37)                    # I2C_SLAVE_FORCE
def wr(r, v):
    try: os.write(i2c, bytes((r, v))); return True
    except OSError: return False
def rd(r):
    try: os.write(i2c, bytes((r,))); return "%02x" % os.read(i2c, 1)[0]
    except OSError: return "--"
mfd = os.open("/dev/mem", os.O_RDWR | os.O_SYNC)
gpio = mmap.mmap(mfd, 0x1000, mmap.MAP_SHARED, mmap.PROT_READ | mmap.PROT_WRITE, offset=0xfe770000)
csi = mmap.mmap(mfd, 0x1000, mmap.MAP_SHARED, mmap.PROT_READ, offset=0xfdfb0000)
r32 = lambda m, o: struct.unpack("<I", m[o:o + 4])[0]
def b2(v):                                        # SWPORT_DR_L bit 10, hiword mask
    gpio[0:4] = struct.pack("<I", (1 << 26) | (v << 10))
def show(t):
    wr(0xfe, 0)
    p = r32(csi, 0x14)
    print("%-30s B2=%d | id %s%s 0xfc=%s 0x3e=%s 0x41=%s | PHY_STATE 0x%03x HS clock %s | ERR1 0x%x"
          % (t, (r32(gpio, 0x70) >> 10) & 1, rd(0xf0), rd(0xf1), rd(0xfc), rd(0x3e), rd(0x41),
             p, "ACTIVE" if p & 0x100 else "off", r32(csi, 0x20)))
def init_and_stream(tag):
    ok = all(wr(r, v) for r, v in SEQ)
    print("  %s: sequence written %s" % (tag, "OK" if ok else "with I2C ERRORS"))
    wr(0xfe, 0); wr(0x3e, 0x91)
    for i in range(3):
        time.sleep(0.3); show("%s stream on +%d" % (tag, i))
show("as the driver left it")
print("A. B2 LOW")
b2(0); time.sleep(0.05); show("B2 low, 50 ms")
init_and_stream("A")
print("B. B2 HIGH again (fresh edge)")
b2(1); time.sleep(0.05); show("B2 high, 50 ms")
init_and_stream("B")
b2(1)
EOF

echo; echo "--- capture in the background ---"
rm -f cam31.raw
timeout 12 v4l2-ctl -d "$VID" --stream-mmap --stream-count=3 --stream-to=cam31.raw >/dev/null 2>&1 &
BG=$!
sleep 2
python3 /tmp/p25t_pwdn.py
kill $BG 2>/dev/null; wait $BG 2>/dev/null
echo "cam31.raw: $(stat -c %s cam31.raw 2>/dev/null || echo none) bytes"
[ -n "${SUDO_USER:-}" ] && chown "$SUDO_USER": cam31.raw 2>/dev/null
rm -f /tmp/p25t_pwdn.py
echo "=== done ==="
