#!/bin/bash
# test_31.sh - rear camera: is the powerdown pin the other way round?
#
# test_30 (2026-10-07): D-PHY routing is fine (in split mode the receiver
# shows only lanes 0-1, still in stop state), so the rear sensor really
# keeps its lanes idle. Everything matches Android except one thing we
# copied but never proved: the PWDN level. Stock DT and Rockchip's driver
# drive GPIO4_B2 HIGH to run; GalaxyCore says PWDN low = power-down. But if
# this module inverts it, HIGH = power-down - and a powered-down GC sensor
# can still answer its chip ID over I2C while the rest sleeps. That
# matches everything we saw.
#
# While our driver keeps the camera powered (background capture), this:
#  A. drives B2 LOW (GPIO register write, mask-protected, bit 10 only),
#     writes Rockchip's sequence + stream-on, watches the receiver
#  B. drives B2 HIGH again (a fresh power-down/up edge), same sequence,
#     watches again
# Each step reads chip ID, 0x3e, 0x41 and the receiver's HS clock.
# Writes: GPIO4 data register bit 10 (rear powerdown) and the camera sensor.
#
#   cd ~/tests
#   sudo bash test_31.sh | tee result_31.txt

set -u
[ "$(id -u)" -eq 0 ] || { echo "ABORT: run with sudo"; exit 1; }
W=1296; H=972; FMT=SGRBG10_1X10
M=/dev/media0
echo "=== rear camera PWDN polarity (test_31) ==="
date; uname -v

VID=$(media-ctl -d $M -e "rkcif-mipi0-id0")
media-ctl -d $M -V "\"gc5035 2-0037\":0 [fmt:$FMT/${W}x$H field:none]" &&
media-ctl -d $M -V "\"dw-mipi-csi2rx fdfb0000.csi\":0 [fmt:$FMT/${W}x$H field:none]" &&
media-ctl -d $M -V "\"rkcif-mipi0\":0 [fmt:$FMT/${W}x$H field:none]" &&
media-ctl -d $M -V "\"rkcif-mipi0\":1 [fmt:$FMT/${W}x$H field:none crop:(0,0)/${W}x$H]" || echo "WARNING: media-ctl -V failed"
v4l2-ctl -d "$VID" --set-fmt-video=width=$W,height=$H,pixelformat=BA10 >/dev/null

cat > /tmp/p25t_pwdn.py <<'EOF'
